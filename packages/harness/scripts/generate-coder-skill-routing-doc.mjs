#!/usr/bin/env node
/**
 * Generate docs/coder-skill-routing.md from skill routing sources.
 * Source of truth: skills only — never edit the output doc by hand.
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '../../..');

const ENTRY_SKILLS = [
  { priority: 1, name: 'ns-execution-gitlab-issue' },
  { priority: 2, name: 'ns-spec-driven' },
  { priority: 3, name: 'ns-autonomous' },
  { priority: 4, name: 'ns-investigator' },
  { priority: 5, name: 'ns-coder' },
];

function read(path) {
  return readFileSync(join(repoRoot, path), 'utf8');
}

const harnessRouting = read('skills/ns-harness/references/code-skill-routing.md');
const changelog = read('skills/_meta/code-skill-routing-changelog.md');

const mermaidMatch = harnessRouting.match(/```mermaid\n([\s\S]*?)```/);
if (!mermaidMatch) {
  console.error('No mermaid block in skills/ns-harness/references/code-skill-routing.md');
  process.exit(1);
}

const harnessBody = harnessRouting
  .replace(/^# Code skill routing\n+/, '')
  .replace(/\*\*Derived doc:\*\*[\s\S]*?node packages\/harness\/scripts\/generate-coder-skill-routing-doc\.mjs\n```\n+/, '')
  .replace(/## Skill handoffs \(diagram source\)[\s\S]*$/, '')
  .trim();

const entryTriggersSections = ENTRY_SKILLS.map(({ priority, name }) => {
  const content = read(`skills/${name}/references/entry-triggers.md`);
  return `### Priority ${priority} — \`${name}\`\n\nSource: \`skills/${name}/references/entry-triggers.md\`\n\n${content.replace(/^# .+\n+/, '').trim()}`;
}).join('\n\n');

const latestVersion = [...changelog.matchAll(/\| (\d+\.\d+) \|/g)].pop()?.[1] ?? '0.0';
const today = new Date().toISOString().slice(0, 10);

const out = `# Coder skill routing

**Version:** ${latestVersion} (generated)
**Generated:** ${today}

**Do not edit this file manually.** Source of truth lives in skills. Regenerate with:

\`\`\`bash
node packages/harness/scripts/generate-coder-skill-routing-doc.mjs
\`\`\`

## Canonical sources

| Source | Role |
| ------ | ---- |
| \`skills/ns-harness/references/code-skill-routing.md\` | Entry priority, tie-breakers, handoff summary, diagram source |
| \`skills/*/references/entry-triggers.md\` | Per-skill trigger phrases (priorities 1–5) |
| \`skills/*/SKILL.md\` routing sections | Per-skill handoffs out |
| \`skills/_meta/code-skill-routing-changelog.md\` | Doc version history |

---

${harnessBody}

## Entry trigger phrases (from skills)

${entryTriggersSections}

## Skill handoffs (diagram)

Extracted from \`skills/ns-harness/references/code-skill-routing.md\`:

\`\`\`mermaid
${mermaidMatch[1].trim()}
\`\`\`

Engine mode: \`A\` and \`C2\` do not re-enter \`G\` — see \`skills/ns-autonomous/references/routing.md\`.

---

## Changelog

${changelog.replace(/^# .+\n+/, '').trim()}
`;

const outPath = join(repoRoot, 'docs/coder-skill-routing.md');
writeFileSync(outPath, out, 'utf8');
console.log(`Wrote ${outPath} (v${latestVersion})`);
